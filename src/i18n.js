  // Nombre visible de un límite a partir de su clave en la API (five_hour, seven_day, seven_day_opus…).
  function limitName(s, key) {
    if (key === 'five_hour') return s.fiveHour;
    if (key === 'seven_day') return s.week;
    const weekly = key.startsWith('seven_day_');
    const rest = key.replace(/^seven_day_|^five_hour_/, '').replace(/^oauth_/, '').replace(/_/g, ' ');
    const model = rest ? rest[0].toUpperCase() + rest.slice(1) : key;
    return weekly ? s.modelWeek(model) : s.modelFive(model);
  }

  // Mensaje de un error a partir de su código; si no hay traducción, el texto original.
  function errorText(s, err) {
    const f = err && s.errors[err.code];
    if (!f) return (err && err.message) || '';
    return typeof f === 'function' ? f(err.params || {}) : f;
  }

  function create(lang) {
    const code = STR[lang] ? lang : 'en';
    const s = STR[code];
    return { ...s, lang: code, limitName: (key) => limitName(s, key), errorText: (err) => errorText(s, err) };
  }

  // 'auto' sigue el idioma del sistema: español si Windows está en español, inglés para el resto.
  function resolve(pref, systemLocale) {
    if (STR[pref]) return pref;
    return String(systemLocale || '').toLowerCase().startsWith('es') ? 'es' : 'en';
  }

  const api = { create, resolve, languages: Object.keys(STR), STR };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.I18N = api;
